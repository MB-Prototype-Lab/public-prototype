'use strict';
const { tap, type, choose, expect } = require('../dsl.cjs');
const { skipToProfile, CALENDAR_EDGES } = require('../common.cjs');

module.exports = {
  id: 'esf-full',
  title: 'Emergency fund from its Home task: Buddy, every step, save, reopen and save again',
  matrix: 'profiles',
  browser: true,
  clocks: CALENDAR_EDGES,
  steps: p => skipToProfile(p).concat([
    tap({ name: 'Open', near: 'Saving for an emergency' }),
    expect({ screen: 'esfBuild' }),
    tap('Build my fund'),
    type('Rent, dollars a month', '1250'),
    tap('Ask Buddy for help with this screen'),
    tap('Rent'),
    tap('My rent covers utilities'),
    tap('Back to the list'),
    tap('Close Buddy'),
    tap('Continue'),
    choose('Groceries, a month', { index: 3 }),
    choose('Home utilities, a month', { index: 1 }),
    tap('Continue'),
    tap({ name: /^Add it \$\d[\d,]*\/mo$/, nth: 0 }),
    type('Anything else to include, dollars a month', '40'),
    tap('See my number'),
    expect({ screen: 'esfPlan' }),
    tap('9 months'),
    choose('Extra percentage', { index: 2 }),
    type('Amount already saved', '1500'),
    tap('Set my goal'),
    expect({ screen: 'goals' }),
    tap({ name: /^Emergency fund/, role: 'button' }),
    expect({ screen: 'esfBuild' }),
    tap('Build my fund'),
    type('Rent, dollars a month', '1350', { clear: true }),
    tap('Continue'),
    tap('Continue'),
    tap('See my number'),
    expect({ text: /Goal \$\d{1,2},\d{3} still to save/ }),
    tap('Set my goal'),
    expect({ screen: 'goals' }),
    tap({ name: 'Remove', role: 'button', near: 'Emergency fund' }),
    expect({ screen: 'goals' }),
  ]),
};
