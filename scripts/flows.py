def adapt_starter(directory):
    # Only adapt known, unique boot/entry pairs: a silent missed anchor leaves
    # an apparently contained package running unrestricted app navigation.
    nav = directory / 'js/navigation.js'
    boot = directory / 'js/boot.js'
    navigation = nav.read_text() if nav.is_file() else ''
    boot_source = boot.read_text() if boot.is_file() else ''
    calls = list(re.finditer(r'^(bootApp|bootV3)\(\);[ \t]*$', navigation, re.M))
    entries = re.findall(r'\bfunction\s+(appEntryScreen|v3EntryScreen)\s*\(\s*\)\s*\{', boot_source)
    boots = re.findall(r'\bfunction\s+(bootApp|bootV3)\s*\(\s*\)\s*\{', boot_source)
    pairs = {'bootApp': 'appEntryScreen', 'bootV3': 'v3EntryScreen'}
    if (len(calls) != 1 or len(re.findall(r'\b(?:bootApp|bootV3)\s*\(', navigation)) != 1 or
            len(boots) != 1 or len(entries) != 1 or
            calls[0].group(1) != boots[0] or pairs[boots[0]] != entries[0] or
            'mbFlowInstall' in navigation):
        raise ValueError('unsupported source boot/entry anchors: expected exactly one matching '
                         'bootApp/appEntryScreen or bootV3/v3EntryScreen pair and one standalone boot call')
    anchor = calls[0]
    navigation = navigation[:anchor.end()] + '\nmbFlowInstall();' + navigation[anchor.end():]
    html = (directory / 'index.html').read_text()
    html = html.replace('<script src="release-config.js"></script>', '<script src="release-config.js"></script>\n  <script src="flow-config.js"></script>')
    html = html.replace('<script src="js/navigation.js"></script>', '<script src="js/flow.js"></script>\n<script src="js/navigation.js"></script>')
    html = html.replace('<link rel="stylesheet" href="css/keyboard.css">', '<link rel="stylesheet" href="css/keyboard.css">\n<link rel="stylesheet" href="css/flow-tools.css">')
    html = html.replace('<script src="js/flow.js"></script>', '<script src="js/flow-tools.js"></script>\n<script src="js/flow.js"></script>')
    html = html.replace('<div class="page">', '<div class="page admin-collapsed">')
    html = html.replace('<aside class="admin" aria-label="Admin Tools">', '<aside id="flowAdmin" class="admin" aria-label="Admin Tools" hidden>')
    html = html.replace('onclick="state.adminCollapsed=true;render()" title="Collapse admin">‹', 'onclick="mbFlowToolsToggle(false)" aria-label="Close Tools" title="Collapse admin">‹')
    html = html.replace('onclick="state.adminCollapsed=false;render()" title="Expand admin">›', 'onclick="mbFlowToolsToggle(true)" aria-label="Tools" aria-controls="flowAdmin" aria-expanded="false" title="Expand admin">›')
    html = html.replace('onclick="resetUserData()">Reset User Data', 'onclick="mbFlowRestart()">Restart Flow')
    html = html.replace('onclick="refreshPinExit()">Exit Prototype', 'onclick="mbFlowExit()">Exit Flow')
    html = html.replace('<div id="adminNavLog"', '<div id="adminSessionLog" style="margin-bottom:4px;"></div>\n      <div id="adminNavLog"')
    templates = Path(__file__).resolve().parent / 'templates'
    (directory / 'js/flow-tools.js').write_text((templates / 'flow-tools.js').read_text())
    (directory / 'css').mkdir(exist_ok=True)
    (directory / 'css/flow-tools.css').write_text((templates / 'flow-tools.css').read_text())
    # An onboarding-only starter has no shared product header or global menu.
    topbar = directory / 'components/topbar.js'
    if topbar.exists():
        topbar.write_text(topbar.read_text() + '\nrenderTopBar = function () { return ""; };\n')
    (directory / 'index.html').write_text(html)
    nav.write_text(navigation)
    (directory / 'js/flow.js').write_text(GENERIC_RUNTIME.replace('__FLOW_ENTRY_FUNCTION__', entries[0]))
    (directory / 'release-config.js').write_text('window.MB_RELEASE = Object.freeze({tracking: false, selector: "../../index.html"});\n')


def create(root, ident, source, label, purpose):
    if not ID.fullmatch(ident) or len(ident) > 64:
        raise ValueError('ID must be lowercase kebab-case, at most 64 characters')
    if not SHA.fullmatch(source) or git(root, 'rev-parse', source + '^{commit}').decode().strip() != source:
        raise ValueError('source must be an existing full commit SHA; checkpoint intended app changes first')
    base = git(root, 'rev-parse', 'HEAD').decode().strip()
    flows = root / 'flows'
    if flows.is_symlink():
        raise ValueError('flows/ must not be a symlink')
    flows.mkdir(exist_ok=True)
    dest = flows / ident
    if os.path.lexists(dest):
        raise ValueError(f'{dest}: destination exists; choose another ID, never overwrite a Flow')
    packages(root)  # Detect malformed prior discovery before exporting.
    temporary = Path(tempfile.mkdtemp(prefix='.creating-', dir=flows))
    stage = temporary / ident
    stage.mkdir()
    installed = False
    try:
        entries = git(root, 'ls-tree', '-rz', source, 'app/').split(b'\0')
        for entry in entries:
            if not entry:
                continue
            info, raw = entry.split(b'\t', 1)
            mode, kind, blob = info.decode().split()
            rel = PurePosixPath(raw.decode()).relative_to('app')
            if mode == '120000' or kind != 'blob':
                raise ValueError(f'app/{rel}: linked/non-file source is forbidden')
            if '..' in rel.parts or any(p.startswith('.') for p in rel.parts):
                continue
            if rel.parts[0] == 'docs' or rel.suffix.lower() not in STATIC_EXTENSIONS:
                continue
            target = stage / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(git(root, 'cat-file', 'blob', blob))
        m = dict(schema=1, id=ident, label=label, purpose=purpose, reference=None, source_app_commit=source, task_base=base, entry='onboarding', completion='onboarding', allowed_screens=['onboarding'], setup_steps=[], profile_behavior='Source onboarding defaults; configure explicit setup and completion before participant use.', proposed_differences=['Contained onboarding starter; unrelated routes are blocked.'])
        (stage / 'flow.json').write_text(json.dumps(m, indent=2) + '\n')
        metadata(stage / 'flow.json')
        (stage / 'flow-config.js').write_text(wrapper('MB_FLOW', m))
        adapt_starter(stage)
        check_package(stage, m)
        if os.path.lexists(dest):
            raise ValueError(f'{dest}: destination appeared during creation; refusing overwrite')
        os.rename(stage, dest)
        installed = True
        catalog(root)
    except BaseException:
        if installed:
            shutil.rmtree(dest)
        raise
    finally:
        shutil.rmtree(temporary)


def is_commit(root, ref):
    return subprocess.run(['git', '-C', str(root), 'rev-parse', '--verify', '--quiet', ref + '^{commit}'], capture_output=True).returncode == 0


def scope(root, selected_scope, against=None):
    """Compare app/ with the merge base of main and HEAD; return (ref, base).

    The merge base moves with each sync of main, so app changes merged in from main
    never count as this task's own edits.
    """
    if against is None:
        against = next((ref for ref in ('origin/main', 'main') if is_commit(root, ref)), None)
        if against is None:
            raise ValueError('no origin/main or main to compare with; name the main this branch merged with --against REF')
    elif not is_commit(root, against):
        raise ValueError(f'--against {against!r} is not a commit')
    # A shallow clone lacks the history a merge base needs, whatever ref is named.
    if git(root, 'rev-parse', '--is-shallow-repository').decode().strip() == 'true':
        raise ValueError('this clone is shallow, so its merge base with main is unknown; run git fetch --unshallow, then retry')
    try:
        base = git(root, 'merge-base', against, 'HEAD').decode().strip()
    except ValueError:
        raise ValueError(f'{against} and HEAD share no history; name the main this branch merged with --against REF') from None
    changed = set(git(root, 'diff', '--name-only', base, '--', 'app').decode().splitlines())
    # A worktree restored to baseline can hide a different staged version. Check
    # the index separately because that version is what the next commit records.
    changed.update(git(root, 'diff', '--cached', '--name-only', base, '--', 'app').decode().splitlines())
    changed.update(git(root, 'ls-files', '--others', '--exclude-standard', 'app').decode().splitlines())
    if changed and selected_scope == 'flow':
        raise ValueError(f'Flow scope changes app/ since {base[:12]} (merge base of {against} and HEAD): '
                         + ', '.join(sorted(changed)) + '. If main made these changes, merge it into this branch '
                         'or pass --against the ref you merged; never revert main\'s work. Undo only this task\'s '
                         'own app edits, and use --scope app-integration only for an approved integration.')
    return against, base


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    subs = parser.add_subparsers(dest='command', required=True)
    make = subs.add_parser('create')
    for name in ('id', 'source', 'label', 'purpose'):
        make.add_argument('--' + name, required=True)
    subs.add_parser('catalog')
    verify = subs.add_parser('check')
    verify.add_argument('--id')
    guard = subs.add_parser('scope')
    guard.add_argument('--against', metavar='REF', help='the main this branch merged (default: origin/main if present, else main)')
    guard.add_argument('--scope', choices=['flow', 'app-integration'], required=True)
    args = parser.parse_args()
    root = Path(git(Path.cwd(), 'rev-parse', '--show-toplevel').decode().strip())
    if args.command == 'create':
        create(root, args.id, args.source, args.label, args.purpose)
    elif args.command == 'catalog':
        catalog(root)
    elif args.command == 'check':
        check(root, args.id)
    else:
        ref, base = scope(root, args.scope, args.against)
        print(f'Flows scope: compared app/ with {base[:12]}, the merge base of {ref} and HEAD')
    print('Flows ' + args.command + ': OK')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, KeyError, json.JSONDecodeError) as error:
        raise SystemExit('Flows error: ' + str(error))
