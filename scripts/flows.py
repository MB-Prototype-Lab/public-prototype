#!/usr/bin/env python3
"""Committed, standalone Flow packages. Never writes app/."""
import argparse
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import tempfile
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
ID = re.compile(r'[a-z0-9]+(?:-[a-z0-9]+)*\Z')
STATIC_EXTENSIONS = {'.html', '.js', '.css', '.json', '.svg', '.png', '.jpg', '.jpeg', '.gif', '.webp', '.ico', '.wav', '.mp3', '.mp4', '.ogg', '.woff', '.woff2', '.ttf'}
SHA = re.compile(r'[0-9a-f]{40}\Z')


def git(root, *args):
    result = subprocess.run(['git', '-C', str(root), *args], capture_output=True)
    if result.returncode:
        raise ValueError(result.stderr.decode().strip())
    return result.stdout


def wrapper(name, value):
    return '// Generated by scripts/flows.py catalog; do not edit.\nwindow.' + name + ' = ' + json.dumps(value, ensure_ascii=True, indent=2) + ';\n'


def metadata(path):
    if path.is_symlink():
        raise ValueError(f'{path}: symlinks are forbidden')
    return validate_metadata(json.loads(path.read_text()), path.parent.name)


def validate_metadata(value, expected_id):
    path = 'flow.json (' + str(expected_id) + ')'
    required = {'schema', 'id', 'label', 'purpose', 'reference', 'source_app_commit', 'task_base', 'entry', 'completion', 'allowed_screens', 'setup_steps', 'profile_behavior', 'proposed_differences'}
    if not isinstance(value, dict) or not required <= value.keys() or value['schema'] != 1:
        raise ValueError(f'{path}: expected schema 1 and all required metadata fields')
    if not isinstance(value['id'], str) or len(value['id']) > 64 or not ID.fullmatch(value['id']) or value['id'] != expected_id:
        raise ValueError(f'{path}: unsafe or mismatched Flow ID')
    for key in ['label', 'purpose', 'profile_behavior', 'entry', 'completion']:
        if not isinstance(value[key], str) or not value[key].strip():
            raise ValueError(f'{path}: {key} must be nonempty text')
    if value['reference'] is not None and not isinstance(value['reference'], str):
        raise ValueError(f'{path}: reference must be text or null')
    for key in ['source_app_commit', 'task_base']:
        if not isinstance(value[key], str) or not SHA.fullmatch(value[key]):
            raise ValueError(f'{path}: {key} must be a full commit SHA')
    for key in ['allowed_screens', 'setup_steps', 'proposed_differences']:
        if not isinstance(value[key], list) or any(not isinstance(x, str) or not x for x in value[key]):
            raise ValueError(f'{path}: {key} must be a list of nonempty strings')
    if len(set(value['allowed_screens'])) != len(value['allowed_screens']) or not {value['entry'], value['completion']} <= set(value['allowed_screens']):
        raise ValueError(f'{path}: entry/completion must be in a unique allowlist')
    return value


def packages(root):
    directory = root / 'flows'
    if directory.is_symlink():
        raise ValueError('flows/ must not be a symlink')
    result = []
    if directory.exists():
        for child in sorted(directory.iterdir()):
            if child.name.startswith('.'):
                continue
            if child.is_symlink():
                raise ValueError(f'{child}: symlinks are forbidden')
            if child.is_dir():
                if not (child / 'flow.json').is_file():
                    raise ValueError(f'{child}: missing flow.json; finish or remove the incomplete package')
                result.append((child, metadata(child / 'flow.json')))
    return result


def catalog_value(items):
    return {'schema': 1, 'flows': [{'id': m['id'], 'label': m['label'], 'description': m['purpose'], 'path': f"flows/{m['id']}/index.html"} for _, m in items]}


def atomic_write(path, content):
    fd, name = tempfile.mkstemp(prefix='.' + path.name, dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as handle:
            handle.write(content)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def catalog(root):
    (root / 'flows').mkdir(exist_ok=True)
    items = packages(root)
    # Validate everything before changing a wrapper or discovery file.
    for directory, _ in items:
        check_dependencies(directory)
    writes = {directory / 'flow-config.js': wrapper('MB_FLOW', m) for directory, m in items}
    value = catalog_value(items)
    writes[root / 'flows/catalog.json'] = json.dumps(value, indent=2) + '\n'
    writes[root / 'flows/catalog.js'] = wrapper('MB_FLOWS', value)
    previous = {p: p.read_bytes() if p.exists() else None for p in writes}
    try:
        for path, content in writes.items():
            atomic_write(path, content)
    except BaseException:
        for path, content in previous.items():
            if content is None:
                path.unlink(missing_ok=True)
            else:
                path.write_bytes(content)
        raise


def resolve_dependency(package, source, raw, dynamic=False):
    raw = unquote(raw.strip())
    if not raw or raw.startswith(('#', 'data:', 'blob:', 'mailto:', 'tel:')):
        return
    parsed = urlsplit(raw)
    if parsed.scheme or parsed.netloc or raw.startswith('/') or '\\' in raw:
        # External web links are navigation only; callers filter these explicitly.
        raise ValueError(f'{source}: forbidden dependency {raw!r}')
    rel = parsed.path
    if not rel:
        return
    if '..' in PurePosixPath(rel).parts:
        raise ValueError(f'{source}: traversal dependency {raw!r}')
    target = (source.parent / rel) if source.suffix == '.css' else (package / rel)
    if source.suffix in ('.html', '.htm'):
        target = source.parent / rel
    if not target.resolve().is_relative_to(package.resolve()):
        raise ValueError(f'{source}: dependency leaves package: {raw!r}')
    if not target.exists() and dynamic and raw == 'assets/audio/onboarding' and source.name == 'onboarding.js':
        return  # Source documents optional generated audio with speech/silence fallback.
    if not target.exists():
        raise ValueError(f'{source}: missing dependency {raw!r}')
    if dynamic and not target.is_dir():
        raise ValueError(f'{source}: dynamic asset prefix must name a directory: {raw!r}')


def check_dependencies(package):
    """Validate paths, plus the app's string-based dynamic assets.

    Dynamic prefixes such as assets/audio/onboarding/ must exist; runtime smoke
    tests check the chosen suffix. This intentionally is not a JS dependency slicer.
    """
    sources = list(package.rglob('*'))
    for source in sources:
        if source.is_symlink():
            raise ValueError(f'{source}: symlinks are forbidden')
    for source in sources:
        if not source.is_file() or source.suffix not in ('.html', '.htm', '.css', '.js', '.json'):
            continue
        text = source.read_text()
        if source.suffix in ('.html', '.htm'):
            for tag in re.finditer(r'<([a-zA-Z][a-zA-Z0-9]*)\b([^>]+)>', text):
                for match in re.finditer(r'\b(src|href|poster)\s*=\s*([\"\'])(.*?)\2', tag.group(2), re.I):
                    attr, _, raw = match.groups()
                    anchor = tag.group(1).lower() == 'a' and attr.lower() == 'href'
                    if anchor and raw.startswith(('https://', 'http://', 'mailto:', 'tel:')):
                        continue
                    if anchor and raw == '../../index.html':
                        continue
                    resolve_dependency(package, source, raw)
        if source.suffix == '.css':
            for raw in re.findall(r'url\(\s*[\"\']?([^\s)\"\']+)', text):
                resolve_dependency(package, source, raw)
            for raw in re.findall(r'@import\s+[\"\']([^\"\']+)', text):
                resolve_dependency(package, source, raw)
        if source.suffix in ('.js', '.json', '.html', '.htm'):
            # Comments may document obsolete paths, so only inspect string literals.
            clean = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
            clean = re.sub(r'(?m)^\s*//[^\n]*$', '', clean)
            for match in re.finditer(r'([\"\'`])([^\"\'`\n]+)\1', clean):
                raw = match.group(2)
                if raw == '../../index.html' and (source.name in ('flow.js', 'release-config.js') or source.suffix in ('.html', '.htm')):
                    continue
                if re.match(r'(?:\.\.?/|/|file:|[A-Za-z]:[\\/]|(?:app|flows)/)', raw) and re.search(r'\.(?:js|css|html|png|svg|wav|mp3|mp4)(?:[?#]|$)', raw):
                    resolve_dependency(package, source, raw)
                if raw.startswith('assets/'):
                    prefix = raw.split('${', 1)[0]
                    dynamic = prefix.endswith('/') or not PurePosixPath(prefix).suffix
                    resolve_dependency(package, source, prefix.rstrip('/'), dynamic)
            # Assets embedded inside generated HTML strings use the same root convention.
            for raw in re.findall(r'assets/[A-Za-z0-9_./%${}-]+', clean):
                prefix = raw.split('${', 1)[0]
                if prefix.endswith('/') or not PurePosixPath(prefix).suffix:
                    resolve_dependency(package, source, prefix.rstrip('/'), True)
                else:
                    resolve_dependency(package, source, prefix)


def validate_dependencies(files, selector='../../index.html'):
    """Validate a committed export without reading mutable checkout files."""
    with tempfile.TemporaryDirectory(prefix='flow-boundaries-') as temporary:
        package = Path(temporary)
        for name, content in files.items():
            relative = PurePosixPath(name)
            if relative.is_absolute() or '..' in relative.parts or '\\' in name:
                raise ValueError(f'unsafe package path {name!r}')
            target = package / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        check_dependencies(package)


def check(root, ident=None):
    items = packages(root)
    if ident is not None and ident not in [m['id'] for _, m in items]:
        raise ValueError(f'unknown Flow {ident!r}')
    value = catalog_value(items)
    for path, expected in [(root / 'flows/catalog.json', json.dumps(value, indent=2) + '\n'), (root / 'flows/catalog.js', wrapper('MB_FLOWS', value))]:
        if not path.is_file() or path.read_text() != expected:
            raise ValueError(f'{path}: stale discovery metadata; run python3 scripts/flows.py catalog')
    for directory, m in items:
        if ident and m['id'] != ident:
            continue
        check_package(directory, m)


def check_package(directory, m):
    # Shared by committed checks and the temporary create stage.
    check_dependencies(directory)  # Reject links before reading policy/entry.
    if (directory / 'flow-config.js').read_text() != wrapper('MB_FLOW', m):
        raise ValueError(f'{directory}: stale policy wrapper; run python3 scripts/flows.py catalog')
    for required in ['index.html', 'release-config.js', 'js/flow.js']:
        if not (directory / required).is_file():
            raise ValueError(f'{directory}: missing {required}')
    html = (directory / 'index.html').read_text()
    scripts = re.findall(r'<script\b[^>]*\bsrc\s*=\s*["\']([^"\']+)["\']', html, re.I)
    required_scripts = ['release-config.js', 'flow-config.js', 'js/refresh-pin.js', 'js/config.js', 'js/boot.js', 'js/flow.js', 'js/navigation.js']
    if any(scripts.count(name) != 1 for name in required_scripts):
        raise ValueError(f'{directory}: entry must load each required configuration/runtime script exactly once '
                         '(the source app commit must include js/refresh-pin.js)')
    if not (scripts.index('release-config.js') < scripts.index('js/refresh-pin.js') < scripts.index('js/config.js') and
            scripts.index('flow-config.js') < scripts.index('js/config.js') and
            scripts.index('js/boot.js') < scripts.index('js/flow.js') < scripts.index('js/navigation.js')):
        raise ValueError(f'{directory}: policy must load before app config, runtime before navigation boot')
    registry = directory / 'js/state.js'
    if not registry.is_file():
        raise ValueError(f'{directory}: missing js/state.js, whose destinations registry declares the screens')
    literal = re.search(r'^const destinations\s*=\s*\[(.*?)^\];', registry.read_text(), re.S | re.M)
    if not literal:
        raise ValueError(f'{registry}: no "const destinations = [...];" screen registry to check allowed_screens against')
    declared = set(re.findall(r'\[\s*[\"\']([^\"\']+)[\"\']\s*,', literal.group(1)))
    undeclared = sorted(set(m['allowed_screens']) - declared)
    if undeclared:
        raise ValueError(f'{directory}: allowed_screens not in the js/state.js destinations registry: ' + ', '.join(undeclared))


